"""
feasibility.py - Data audit, prompt selection and training smoke tests for the feasibility review.

Project : Expert-to-layperson translation of radiology reports with FLAN-T5,
          LoRA vs. full fine-tuning (COMP3710 Pattern Analysis, Project 2.6, Hard).

Produces the "Preliminary Feasibility Evidence" for the midpoint check-off
(results/feasibility.md):
  * data audit: rows and sources per split, report / summary lengths in words and tokens,
    duplicated reports, share of validation reports that also occur in training;
  * prompt selection: zero-shot ROUGE, copy rate and empty-output rate of four instruction
    wordings on dev reports (the best one is the fixed prompt in config.py);
  * LoRA and full fine-tuning smoke tests: loss trend over a few steps, time per step,
    tokens/s, peak GPU memory, trainable parameters, projected minutes per epoch.

Usage (GPU node):  python feasibility.py            (CPU test: add --device cpu --model google/flan-t5-small)
"""

import argparse
import os
import time

import numpy as np
import torch

from config import CANDIDATE_PROMPTS
from dataset import (DEFAULT_DATA_DIR, DEFAULT_MODEL, LaySummDataset, audit_text, load_tokenizer,
                     make_train_loader, normalise_report, prepare_splits)
from modules import LaySummariser, count_parameters
from train import make_optimizer, param_groups
from utils import (autocast_ctx, get_device, library_versions, md_table, peak_memory_mb,
                   reset_peak_memory, rouge_per_example, set_seed)


def parse_args():
    p = argparse.ArgumentParser(description="Feasibility evidence: audit + prompt selection + smoke tests")
    p.add_argument("--data-dir", default=DEFAULT_DATA_DIR)
    p.add_argument("--model", default=DEFAULT_MODEL)
    p.add_argument("--prompt-samples", type=int, default=128, help="dev reports per candidate prompt")
    p.add_argument("--smoke-steps", type=int, default=40, help="optimiser steps per smoke test")
    p.add_argument("--batch-size", type=int, default=32)
    p.add_argument("--max-tokens", type=int, default=5120, help="as in train.py")
    p.add_argument("--out", default="results")
    p.add_argument("--device", default="auto", choices=["auto", "cpu"])
    return p.parse_args()


def smoke_test(mode: str, args, tokenizer, train_ds, device, amp: bool, steps_per_epoch: int):
    """A few optimiser steps of real training: does the loss fall, how fast, how much memory?"""
    set_seed(0)
    model = LaySummariser(args.model, mode).to(device)
    total, trainable = count_parameters(model)
    lr = 1e-3 if mode == "lora" else 1e-4          # the train.py defaults
    opt = make_optimizer(param_groups(model, 0.01), lr, device)
    loader = make_train_loader(train_ds, args.batch_size, tokenizer.pad_token_id, seed=0, num_workers=0,
                               max_tokens=args.max_tokens or None)
    reset_peak_memory(device)
    losses, tokens, start = [], 0, None
    model.train()
    for step, batch in enumerate(loader):
        if step == 3:  # skip warm-up steps (kernel selection) in the timing
            if device.type == "cuda":
                torch.cuda.synchronize()
            start, tokens = time.time(), 0
        batch = {k: v.to(device) for k, v in batch.items()}
        with autocast_ctx(device, amp):
            loss = model(**batch).loss
        loss.backward()
        torch.nn.utils.clip_grad_norm_([p for p in model.parameters() if p.requires_grad], 1.0)
        opt.step()
        opt.zero_grad(set_to_none=True)
        losses.append(loss.item())
        tokens += int(batch["attention_mask"].sum()) + int((batch["labels"] >= 0).sum())
        if step + 1 >= args.smoke_steps:
            break
    if device.type == "cuda":
        torch.cuda.synchronize()
    measured = max(1, len(losses) - 3)
    step_s = (time.time() - start) / measured if start else float("nan")
    k = max(1, min(10, len(losses) // 4))
    result = {"mode": mode, "params": total, "trainable": trainable,
              "loss_first": float(np.mean(losses[:k])), "loss_last": float(np.mean(losses[-k:])),
              "step_ms": 1000 * step_s, "tokens_per_s": tokens / max(1e-9, step_s * measured),
              "peak_mb": peak_memory_mb(device), "epoch_min": steps_per_epoch * step_s / 60}
    del model, opt
    if device.type == "cuda":
        torch.cuda.empty_cache()
    return result


def main():
    args = parse_args()
    device = get_device(args.device)
    amp = device.type == "cuda"
    os.makedirs(args.out, exist_ok=True)
    tokenizer = load_tokenizer(args.model)
    lines = ["# Feasibility evidence (auto-generated by feasibility.py)", "",
             f"Device: {device}" + (f" ({torch.cuda.get_device_name(0)})" if device.type == "cuda" else "")
             + f"; model {args.model}; versions: " + ", ".join(f"{k} {v}" for k, v in library_versions().items()), ""]

    # ---- data audit -------------------------------------------------------------------
    t0 = time.time()
    lines += ["## Data audit", "", audit_text(args.data_dir, tokenizer), ""]
    splits = prepare_splits(args.data_dir)
    lines.append(f"After de-duplication and the report-grouped dev split: train {len(splits['train']):,} rows, "
                 f"dev {len(splits['dev']):,} rows (no report text shared with train). "
                 f"Audit time {time.time() - t0:.0f}s.")

    # ---- prompt selection (zero-shot, dev reports only) ---------------------------------------
    dev = splits["dev"].head(args.prompt_samples)
    zs = LaySummariser(args.model, mode="zeroshot").to(device).eval()
    rows = []
    for name, template in CANDIDATE_PROMPTS.items():
        t1 = time.time()
        outs = zs.summarise(dev["radiology_report"].tolist(), tokenizer, device, batch_size=32,
                            max_new_tokens=160, amp=amp, prompt_template=template)
        summaries = [o["summary"] for o in outs]
        sc = rouge_per_example(summaries, dev["layman_report"].tolist())
        copy = np.mean([normalise_report(s) == normalise_report(r) for s, r in zip(summaries, dev["radiology_report"])])
        empty = np.mean([not s.strip() for s in summaries])
        rows.append([name, f"{sc['rouge1'].mean():.3f}", f"{sc['rougeLsum'].mean():.3f}", f"{100 * copy:.0f}%",
                     f"{100 * empty:.0f}%", f"{(time.time() - t1) / len(dev) * 1000:.0f}"])
    best = max(rows, key=lambda r: float(r[2]))
    translate = next(r for r in rows if r[0] == "translate")
    best_prompt_note = (f"Best zero-shot prompt here: '{best[0]}' (ROUGE-Lsum {best[2]}); the fixed prompt used "
                        f"everywhere is 'translate' (config.PROMPT_TEMPLATE, ROUGE-Lsum {translate[2]}). If another "
                        "prompt is better by more than 0.02 with flan-t5-base, set PROMPT_TEMPLATE to it in config.py "
                        "BEFORE training, so the zero-shot baseline is as strong as possible.")
    copy_scores = rouge_per_example(dev["radiology_report"].tolist(), dev["layman_report"].tolist())
    rows.append(["(copy the report unchanged)", f"{copy_scores['rouge1'].mean():.3f}",
                 f"{copy_scores['rougeLsum'].mean():.3f}", "100%", "0%", "0"])
    del zs
    lines += ["", f"## Prompt selection (zero-shot {args.model}, {len(dev)} dev reports, greedy decoding)", "",
              md_table(["Prompt", "ROUGE-1", "ROUGE-Lsum", "Exact copy of report", "Empty output", "ms/report"], rows),
              "", best_prompt_note]

    # ---- smoke tests ------------------------------------------------------------------------
    smoke_df = splits["train"].sample(n=min(len(splits["train"]), args.batch_size * (args.smoke_steps + 5)),
                                      random_state=0)
    smoke_ds = LaySummDataset(smoke_df, tokenizer)
    steps_per_epoch = len(splits["train"]) // args.batch_size
    results = [smoke_test(m, args, tokenizer, smoke_ds, device, amp, steps_per_epoch) for m in ("lora", "full")]
    lines += ["", f"## Training smoke tests ({args.smoke_steps} steps, batch {args.batch_size}, "
                  f"{'bf16 autocast' if amp else 'fp32'})", "",
              md_table(["Mode", "Parameters", "Trainable", "Loss (first -> last steps)", "ms/step", "tokens/s",
                        "Peak GPU memory (MB)", f"Projected min/epoch ({steps_per_epoch:,} steps)"],
                       [[r["mode"], f"{r['params']:,}", f"{r['trainable']:,} ({100 * r['trainable'] / r['params']:.2f}%)",
                         f"{r['loss_first']:.3f} -> {r['loss_last']:.3f}", f"{r['step_ms']:.0f}",
                         f"{r['tokens_per_s']:.0f}", f"{r['peak_mb']:.0f}", f"{r['epoch_min']:.1f}"] for r in results])]

    text = "\n".join(lines) + "\n"
    path = os.path.join(args.out, "feasibility.md")
    with open(path, "w") as f:
        f.write(text)
    print(text)
    print(f"Saved {path}")


if __name__ == "__main__":
    main()
